import { test, expect } from '@playwright/test';

test('savings corrections preserve other entries and remain available on completed goals', async ({ page }, testInfo) => {
  await page.goto('/');
  await page.getByLabel('Il tuo nome').fill('Anna');
  await page.getByLabel('Email', { exact: true }).fill(`goals-${testInfo.project.name}-${Date.now()}@example.test`);
  await page.getByLabel('Password', { exact: true }).fill('test-password-123');
  await page.getByLabel('Nome del vostro spazio').fill('Casa test');
  await page.getByRole('button', { name: 'Entra a casa' }).click();
  await expect(page.getByRole('heading', { name: 'La nostra casa, in ordine.' })).toBeVisible();
  await page.goto('/#goals');
  await page.getByRole('button', { name: 'Nuovo obiettivo' }).click();
  let dialog = page.getByRole('dialog');
  await dialog.getByLabel('Nome dell’obiettivo').fill('Viaggio');
  await dialog.getByLabel('Importo da raggiungere (€)').fill('1000');
  await dialog.getByLabel('Già accantonato (€)').fill('300');
  await dialog.getByRole('button', { name: 'Crea obiettivo' }).click();
  await page.getByRole('button', { name: 'Gestisci risparmi' }).click();
  dialog = page.getByRole('dialog');
  for (const amount of ['200', '100']) {
    await dialog.getByLabel('Quanto avete messo da parte? (€)').fill(amount);
    await dialog.getByRole('button', { name: 'Aggiungi risparmio', exact: true }).click();
    await expect(dialog.getByRole('status')).toHaveText('Risparmio aggiunto.');
    await expect(dialog.getByLabel('Quanto avete messo da parte? (€)')).toHaveValue('');
  }
  await expect(dialog.locator('.contribution-status')).toContainText('600,00');
  await dialog.getByRole('button', { name: /^Modifica accantonamento di 200,/ }).click();
  await dialog.getByLabel('Importo accantonato (€)').fill('50');
  await dialog.getByRole('button', { name: 'Salva importo', exact: true }).click();
  await expect(dialog.locator('.contribution-status')).toContainText('450,00');
  page.on('dialog', browserDialog => browserDialog.accept());
  await dialog.getByRole('button', { name: 'Elimina importo iniziale', exact: true }).click();
  await expect(dialog.locator('.contribution-status')).toContainText('150,00');
  await expect(dialog.locator('.savings-row')).toHaveCount(3);
  await dialog.getByRole('button', { name: /^Elimina accantonamento di 100,/ }).click();
  await expect(dialog.locator('.contribution-status')).toContainText('50,00');
  await dialog.getByRole('button', { name: 'Modifica importo iniziale', exact: true }).click();
  await dialog.getByLabel('Importo iniziale (€)').fill('1000');
  await dialog.getByRole('button', { name: 'Salva importo', exact: true }).click();
  await expect(dialog.locator('.contribution-status')).toContainText('1.050,00');
  await dialog.getByRole('button', { name: 'Chiudi', exact: true }).click();
  await expect(page.locator('.goal-card .badge')).toHaveText('Raggiunto');
  await page.getByRole('button', { name: 'Gestisci risparmi' }).click();
  const viewport = page.viewportSize()!;
  await page.setViewportSize({ width: 320, height: 900 });
  expect(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('risparmi-320.png'), fullPage: true });
  await page.setViewportSize(viewport);
  await dialog.getByRole('button', { name: 'Elimina importo iniziale', exact: true }).click();
  await expect(dialog.locator('.contribution-status')).toContainText('50,00');
  await dialog.getByRole('button', { name: /^Elimina accantonamento di 50,/ }).click();
  await expect(dialog.locator('.savings-row')).toHaveCount(1);
  await expect(dialog.getByRole('button', { name: 'Elimina importo iniziale', exact: true })).toBeDisabled();
  await dialog.getByRole('button', { name: 'Chiudi', exact: true }).click();
  await expect(page.locator('.goal-card')).toContainText('0%');
  await page.reload();
  await expect(page.locator('.goal-card .goal-amount')).toContainText('0,00');
  await page.goto('/#overview');
  await expect(page.getByRole('button', { name: 'Risparmi per gli obiettivi: vai agli obiettivi' })).toContainText('0,00');
});
