import { test, expect, type Page } from '@playwright/test';

async function go(page: Page, label: string) {
  if (await page.getByRole('button', { name: 'Apri menu' }).isVisible()) await page.getByRole('button', { name: 'Apri menu' }).click();
  await page.getByRole('navigation').getByRole('button', { name: label, exact: true }).click();
}

test('a family can manage money, goals, shopping and pinned files on desktop and mobile', async ({ page, browser }, testInfo) => {
  const unique = `${testInfo.project.name}-${Date.now()}`;
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await page.getByLabel('Il tuo nome').fill('Giuseppe');
  await page.getByLabel('Email', { exact: true }).fill(`${unique}@example.it`);
  await page.getByLabel('Password', { exact: true }).fill('test-password-123');
  await page.getByLabel('Nome del vostro spazio').fill('Casa Catalano');
  await page.getByRole('button', { name: 'Entra a casa' }).click();
  await expect(page.getByRole('heading', { name: 'La nostra casa, in ordine.' })).toBeVisible();
  await page.getByRole('button', { name: 'Nuova entrata' }).click();
  let dialog = page.getByRole('dialog');
  await dialog.getByLabel('Nome', { exact: true }).fill('Stipendio');
  await dialog.getByLabel('Importo (€)').fill('3200,00');
  // Only recurring incomes fund the budget: the salary is set as recurring.
  await dialog.getByLabel('Ricorrente (ogni mese)').check();
  await dialog.getByRole('button', { name: 'Aggiungi entrata' }).click();
  await expect(page.locator('.stat-card').first()).toContainText('3.200,00');
  await expect(page.getByRole('button', { name: 'Nuova uscita' }).locator('svg')).toHaveClass(/lucide-minus/);
  await page.getByRole('button', { name: 'Nuova uscita' }).click();
  dialog = page.getByRole('dialog');
  await dialog.getByLabel('Nome', { exact: true }).fill('Affitto');
  await dialog.getByLabel('Importo (€)').fill('850');
  await dialog.getByRole('button', { name: 'Aggiungi uscita' }).click();
  await expect(page.locator('.balance-card')).toContainText('2.350,00');
  await expect(page.locator('.legend-row').first().locator('.legend-amounts')).toHaveText('850,00 €/1.120,00 €');
  await go(page, 'Ripartizione budget');
  await expect(page.locator('.budget-category').first()).toContainText('1.120,00');
  await page.getByRole('button', { name: 'Modifica schema' }).click();
  dialog = page.getByRole('dialog');
  await dialog.getByRole('button', { name: 'Conservativa', exact: true }).click();
  await dialog.getByRole('button', { name: 'Salva schema' }).click();
  await expect(page.locator('.budget-category').first()).toContainText('960,00');
  await expect(page.locator('.budget-category').first()).toContainText('110,00 € ancora disponibili');
  await go(page, 'Obiettivi');
  await page.getByRole('button', { name: 'Nuovo obiettivo' }).click();
  dialog = page.getByRole('dialog');
  await dialog.getByLabel('Nome dell’obiettivo').fill('Viaggio in famiglia');
  await dialog.getByLabel('Importo da raggiungere (€)').fill('2000');
  await dialog.getByLabel('Già accantonato (€)').fill('300');
  await dialog.getByRole('button', { name: 'Crea obiettivo' }).click();
  await page.getByRole('button', { name: 'Gestisci risparmi' }).click();
  dialog = page.getByRole('dialog');
  await dialog.getByLabel('Quanto avete messo da parte? (€)').fill('200');
  await dialog.getByRole('button', { name: 'Aggiungi risparmio' }).click();
  await expect(page.locator('.goal-card')).toContainText('500,00');
  await expect(page.locator('.goal-card')).toContainText('25%');
  await dialog.getByRole('button', { name: 'Chiudi', exact: true }).click();
  await page.getByRole('button', { name: 'Modifica obiettivo Viaggio in famiglia' }).click();
  await page.getByLabel('Importo da raggiungere (€)').fill('2500');
  await page.getByRole('button', { name: 'Salva modifiche' }).click();
  await expect(page.locator('.goal-card')).toContainText('20%');
  await go(page, 'Lista della spesa');
  await page.getByLabel('Prodotto', { exact: true }).fill('Pasta fresca');
  await page.getByLabel('Quantità', { exact: true }).fill('500 g');
  await page.getByRole('button', { name: 'Aggiungi', exact: true }).click();
  await expect(page.locator('.shopping-row')).toContainText('Pasta fresca');
  await page.getByRole('checkbox', { name: 'Segna acquistato: Pasta fresca' }).click();
  await expect(page.getByRole('checkbox', { name: 'Da acquistare: Pasta fresca' })).toHaveAttribute('aria-checked', 'true');
  await go(page, 'Lavagna');
  await page.getByRole('button', { name: 'Nuovo appunto' }).click();
  dialog = page.getByRole('dialog');
  await dialog.getByLabel('Titolo', { exact: true }).fill('Documenti per le vacanze');
  await dialog.getByLabel('Appunto', { exact: true }).fill('Ricordiamoci di controllare i documenti prima di partire.');
  await dialog.getByLabel('Metti in evidenza').check();
  await dialog.locator('input[type=file]').setInputFiles({ name: 'promemoria.txt', mimeType: 'text/plain', buffer: Buffer.from('Documento di prova') });
  await dialog.getByRole('button', { name: 'Pubblica sulla lavagna' }).click();
  await expect(page.locator('.note-card')).toContainText('IN EVIDENZA');
  await expect(page.getByRole('link', { name: 'promemoria.txt' })).toBeVisible();
  await page.locator('.note-card .note-content').click();
  dialog = page.getByRole('dialog', { name: 'Documenti per le vacanze' });
  await expect(dialog).toBeVisible();
  await expect(dialog).toContainText('Ricordiamoci di controllare i documenti prima di partire.');
  await expect(dialog.locator('input, textarea, form')).toHaveCount(0);
  await page.screenshot({ path: testInfo.outputPath('consultazione-nota.png'), fullPage: true });
  await expect(dialog.getByRole('button', { name: /Salva|Modifica|Rimuovi/ })).toHaveCount(0);
  const downloadPromise = page.waitForEvent('download');
  await dialog.getByRole('link', { name: 'promemoria.txt' }).click();
  expect((await downloadPromise).suggestedFilename()).toBe('promemoria.txt');
  await dialog.getByRole('button', { name: 'Chiudi', exact: true }).click();
  await page.getByRole('button', { name: 'Leggi Documenti per le vacanze' }).focus();
  await page.keyboard.press('Enter');
  await expect(page.getByRole('dialog', { name: 'Documenti per le vacanze' })).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('button', { name: 'Rimuovi in evidenza Documenti per le vacanze' }).click();
  await expect(page.getByRole('button', { name: 'Metti in evidenza Documenti per le vacanze' })).toBeVisible();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('button', { name: 'Metti in evidenza Documenti per le vacanze' }).click();
  await expect(page.locator('.note-card')).toContainText('IN EVIDENZA');

  await go(page, 'Impostazioni');
  await page.getByRole('button', { name: 'Genera link di invito' }).click();
  const inviteLink = await page.getByLabel('Link di invito').inputValue();
  await go(page, 'Lavagna');
  const secondContext = await browser.newContext({ viewport: { width: 1280, height: 900 } });
  const second = await secondContext.newPage();
  await second.goto(inviteLink);
  await second.getByLabel('Il tuo nome').fill('Sara');
  await second.getByLabel('Email', { exact: true }).fill(`sara-${unique}@example.it`);
  await second.getByLabel('Password', { exact: true }).fill('test-password-123');
  await expect(second.getByLabel('Codice invito')).not.toHaveValue('');
  await second.getByRole('button', { name: 'Entra a casa' }).click();
  await expect(second.locator('.stat-card').first()).toContainText('3.200,00');
  await go(second, 'Lavagna');
  await expect(second.getByRole('heading', { name: 'Documenti per le vacanze' })).toBeVisible();
  await second.getByRole('button', { name: 'Modifica Documenti per le vacanze' }).click();
  await second.getByLabel('Appunto', { exact: true }).fill('Documenti controllati da Sara.');
  await second.getByRole('button', { name: 'Salva modifiche' }).click();
  await expect(page.locator('.note-content')).toContainText('Documenti controllati da Sara.', { timeout: 20000 });
  await secondContext.close();
  await go(page, 'Uscite');
  await page.getByRole('button', { name: 'Modifica Affitto' }).click();
  await page.getByLabel('Importo (€)').fill('800');
  await page.getByRole('button', { name: 'Salva modifiche' }).click();
  await expect(page.locator('.mini-stats')).toContainText('2.400,00');
  await page.reload();
  await expect(page.locator('.mini-stats')).toContainText('2.400,00');
  const csvPromise = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Esporta CSV' }).click();
  expect((await csvPromise).suggestedFilename()).toBe('movimenti-casa.csv');
  await go(page, 'Panoramica');
  await expect(page.locator('.stat-card').first()).toContainText('3.200,00');
  await expect(page.locator('.daily-panel .daily-row strong')).toHaveText(['Lista della spesa', 'Menu settimanale', 'Conferimento rifiuti', 'Scadenze', 'Lavagna di famiglia']);
  await expect(page.locator('.daily-panel .daily-row').last()).toHaveText('Lavagna di famiglia');
  await expect(page.locator('.daily-divider, .note-peek')).toHaveCount(0);
  await expect(page.locator('.overview-bottom .section-heading h2')).toHaveText(['I nostri prossimi traguardi', 'Gli ultimi movimenti']);
  await expect(page.locator('.legend-row').first().locator('.legend-amounts')).toHaveText('800,00 €/960,00 €');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('panoramica.png'), fullPage: true });
  const viewport = page.viewportSize()!;
  for (const width of [320, 1100]) {
    await page.setViewportSize({ width, height: 900 });
    await page.locator('.sidebar').evaluate(async element => { await Promise.all(element.getAnimations().map(animation => animation.finished)); });
    expect(await page.locator('.legend-row').evaluateAll(rows => rows.every(row => {
      const category = row.querySelector('.legend-category')!.getBoundingClientRect();
      const amounts = row.querySelector('.legend-amounts')!.getBoundingClientRect();
      const bounds = row.getBoundingClientRect();
      const spans = Array.from(row.querySelectorAll('.legend-amounts > *'));
      return amounts.left >= category.right && amounts.right <= bounds.right + 1 && spans.every(item => item.getBoundingClientRect().right <= bounds.right + 1);
    }))).toBe(true);
    expect(await page.locator('.donut span').evaluate(el => getComputedStyle(el).fontSize)).toBe(await page.locator('.donut small').evaluate(el => getComputedStyle(el).fontSize));
    const quickActions = page.locator('.dashboard-quick-actions .button');
    const incomeAction = await quickActions.nth(0).boundingBox();
    const expenseAction = await quickActions.nth(1).boundingBox();
    // Hover can lift a button by 1 px; both actions must still share the same row.
    expect(Math.abs(incomeAction!.y - expenseAction!.y)).toBeLessThanOrEqual(2);
    expect(await quickActions.nth(0).evaluate(button => getComputedStyle(button).backgroundColor)).not.toBe(await quickActions.nth(1).evaluate(button => getComputedStyle(button).backgroundColor));
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await page.screenshot({ path: testInfo.outputPath(`panoramica-${width}.png`), fullPage: true });
  }
  await page.setViewportSize(viewport);
  for (const [index, target] of [[0, 'incomes'], [1, 'expenses'], [2, 'budget'], [3, 'goals']] as const) {
    await page.locator('.stat-card').nth(index).focus();
    await page.keyboard.press('Enter');
    await expect(page).toHaveURL(new RegExp(`#${target}$`));
    await go(page, 'Panoramica');
  }
  await page.locator('.spending-panel .donut').click();
  await expect(page).toHaveURL(/#budget$/);
  await go(page, 'Panoramica');
  await page.locator('.overview-bottom .compact-goals').click();
  await expect(page).toHaveURL(/#goals$/);
  await go(page, 'Panoramica');
  await page.locator('.overview-bottom .transaction-description').first().click();
  await expect(page).toHaveURL(/#expenses$/);
  await go(page, 'Panoramica');
  expect(errors).toEqual([]);
});
